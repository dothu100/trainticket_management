    void capnhatnguoi()
    {
        jComboBox1.removeAllItems();
        for(nguoiMuaVe i:listnguoi){
            jComboBox1.addItem(i.getMaNguoiMua());
        }
    }
    
    void capnhatve()
    {
        jComboBox2.removeAllItems();
        for(veTau i:listve)
            jComboBox2.addItem(i.getMaVe());
    }
    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        if(Integer.parseInt(txtSoluong.getText())<0 || txtSoluong.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane," loi nhap so luong");
        }
        hoaDon a = new hoaDon(listnguoi.get(jComboBox1.getSelectedIndex()),
                listve.get(jComboBox2.getSelectedIndex()),Integer.parseInt(txtSoluong.getText()));
        a.setSoTienTra(Integer.parseInt(txtSoluong.getText())*a.getBt().getDonGia());
        boolean ok = true;
        for(hoaDon i :listhd){
            if(i.getNguoimua().getMaNguoiMua().equals(jComboBox1.getSelectedItem().toString())
                    && i.getBt().getMaVe().equals(a.getBt().getMaVe())){
                i.setSoluong(i.getSoluong()+Integer.parseInt(txtSoluong.getText()));
                ok = false;
                new io().ghihoadon(listhd);
               taohd();
            }
        }
        if(ok){
            listhd.add(a);
        }
        new io().ghihoadon(listhd);
        taohd();
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        for (int i = 0; i <listhd.size()-1; i++) {
            for (int j =i+1; j < listhd.size(); j++) {
                if(listhd.get(i).getSoluong()<listhd.get(j).getSoluong())
                {
                    Collections.swap(listhd, i, j);
                }
            }
        }
        taohd();
    }//GEN-LAST:event_jButton4ActionPerformed

