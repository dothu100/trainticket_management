    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(txtHoten.getText().isEmpty() || txtDiachi.getText().isEmpty()||txtManguoimua.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane,"thieu du kien");
        }
        else{
            try{
                nguoiMuaVe a = new nguoiMuaVe(txtHoten.getText(),txtDiachi.getText(), txtManguoimua.getText(),
                        cbNhomnguoimua.getSelectedItem().toString());
                if(listnguoi.contains(a)){
                    JOptionPane.showMessageDialog(rootPane, " trung ma");
                }
                else{
                    listnguoi.add(a);
                }
                new io().ghinguoimua(listnguoi);
                taobangnguoi();
            }
            catch(Exception e){
                JOptionPane.showMessageDialog(rootPane, e.getMessage());
            }
        }
        capnhatnguoi();
    }//GEN-LAST:event_jButton1ActionPerformed

